"""Isolated, short-lived Hermes/document worker. JSON on stdin/stdout only.

Use the bundled venv. The parent creates a fresh HERMES_HOME on the stick for
each invocation; this process never imports the general edition's config.
"""
import contextlib
import importlib.util
import json
import logging
import os
from pathlib import Path
import sys
import threading

sys.path.insert(0, str(Path(__file__).resolve().parent))
from recruit_core import RecruitError, extract_upload


def install_call_budget(agent, limit):
    """Cap *all* completions, including Hermes' extra iteration-summary calls.

    max_iterations alone does not cap those calls. Wrap rebuilt clients as well,
    and turn off SDK retries so one create() means at most one HTTP attempt.
    The wrapper lives only on this short-lived worker's agent/client instances.
    """
    budget = {"used": 0, "denied": False}
    lock = threading.Lock()

    def guard(client):
        if getattr(client, "_recruit_budget", None) is budget:
            return client
        client.max_retries = 0
        original = client.chat.completions.create

        def create(*args, **kwargs):
            with lock:
                if budget["used"] >= limit:
                    budget["denied"] = True
                    raise RecruitError("本次模型调用已达上限，请简化需求后重试；本次已计入额度。")
                budget["used"] += 1
            return original(*args, **kwargs)

        client.chat.completions.create = create
        client._recruit_budget = budget
        return client

    guard(agent.client)
    original_factory = agent._create_openai_client

    def factory(*args, **kwargs):
        return guard(original_factory(*args, **kwargs))

    agent._create_openai_client = factory
    return budget


def run_agent_job(job, agent_class=None):
    # No inherited provider defaults, project context, plugins, memory, retries
    # or background calls. The config is generated by our parent, not the model.
    if agent_class is None:
        spec = importlib.util.find_spec("run_agent")
        if spec is None:
            raise RecruitError("未安装 Hermes 引擎，请先运行安装脚本。")
        if spec.origin and Path(spec.origin).with_name(".env").exists():
            raise RecruitError("引擎目录存在额外 .env 文件，请由管理员移走后重启招聘版。")
        from run_agent import AIAgent
        agent_class = AIAgent
    config = job["config"]
    allow_tools = config["allow_tools"]
    agent = agent_class(
        provider="deepseek", api_mode="chat_completions",
        base_url="https://api.deepseek.com/v1", api_key=job["api_key"],
        model=config["model"], enabled_toolsets=["terminal", "file"] if allow_tools else [],
        skip_context_files=True, skip_memory=True, skip_background_review=True,
        load_soul_identity=False, save_trajectories=False, quiet_mode=True,
        max_iterations=3 if allow_tools else 1, max_tokens=config["max_tokens"],
        reasoning_config={"enabled": False}, run_budget_seconds=120,
        fallback_model=None, session_db=None, checkpoints_enabled=False,
        cwd=os.getcwd(),
    )
    try:
        if not allow_tools and (agent.tools or agent.valid_tool_names):
            raise RecruitError("引擎工具权限检查失败，已停止本次请求；请联系管理员。")
        budget = install_call_budget(agent, 3 if allow_tools else 1)
        result = agent.run_conversation(job["user"], system_message=job["system"], conversation_history=[])
        if budget["denied"]:
            raise RecruitError("模型未完成回答且本次调用已达上限；请简化需求后重试，本次已计入额度。")
        if not isinstance(result, dict) or result.get("failed") or not result.get("completed"):
            raise RecruitError("模型未完成回答。请检查 Key、余额和模型权限后重试；本次已计入额度。")
        answer = result.get("final_response")
        if not isinstance(answer, str) or not answer.strip():
            raise RecruitError("模型返回空内容，请稍后重试；本次已计入额度。")
        return {"answer": answer}
    finally:
        agent.close()


def main():
    for stream in (sys.stdin, sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="strict")
    logging.disable(logging.CRITICAL)
    extracting = False
    try:
        job = json.load(sys.stdin)
        extracting = job["mode"] == "extract"
        if extracting:
            from recruit_limits import restrict_documents
            try:
                restrict_documents()
            except Exception:
                raise RecruitError("无法启用文档资源限制，请由管理员检查运行环境；本次未计用量。") from None
        # Some upstream imports print diagnostics, which must not corrupt JSON
        # or expose provider exceptions containing keys/prompts to the browser.
        with open(os.devnull, "w", encoding="utf-8") as quiet:
            with contextlib.redirect_stdout(quiet), contextlib.redirect_stderr(quiet):
                result = extract_upload(job["payload"], ocr_enabled=job.get("ocr_enabled", True)) if extracting else run_agent_job(job)
    except RecruitError as exc:
        result = {"error": str(exc)}
    except Exception:
        result = {"error": "文档读取失败或超出内存限制，请缩小图片或拆分 PDF 后重试；本次未计用量。" if extracting else
                  "请求失败，请检查安装、网络、DeepSeek Key、余额和模型权限。模型请求已提交时会保留用量计数。"}
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
